const { chromium } = require('C:/Users/36997/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const target = 'https://hermes-content-review.taild890b1.ts.net:10000/';
const out = __dirname;
(async () => {
  const browser = await chromium.launch({channel:'msedge',headless:true});
  const evidence = {target, browser:'Edge via Playwright; Browser plugin not available', runs:[]};
  try {
    for (const viewport of [{width:1440,height:1000},{width:390,height:844}]) {
      const context = await browser.newContext({viewport});
      const page = await context.newPage();
      const errors = [];
      page.on('pageerror', e => errors.push(String(e)));
      page.on('console', m => {if (m.type()==='error') errors.push(m.text());});
      page.on('response', r => {if (r.status()>=400) errors.push(`${r.status()} ${r.url()}`);});
      const response = await page.goto(target,{waitUntil:'domcontentloaded',timeout:45000});
      assert.equal(response.status(),200);
      assert.equal(await page.title(),'Signal Forge');
      await page.getByRole('navigation',{name:'页面导航'}).getByRole('link',{name:'复盘与诊断',exact:true}).click();
      await page.getByRole('heading',{name:'复盘与诊断',exact:true}).waitFor();
      await page.getByLabel('复盘策略').selectOption('fishing-reversal');
      await page.getByLabel('起始日期',{exact:true}).fill('2026-09-03');
      await page.getByLabel('结束日期',{exact:true}).fill('2026-09-09');
      const resultReady = page.waitForResponse(r => r.url().includes('/api/review/summary?') && r.url().includes('fishing-reversal') && r.url().includes('2026-09-09'));
      await page.getByRole('button',{name:'查询复盘',exact:true}).click();
      const resultResponse = await resultReady;
      assert.equal(resultResponse.status(),200);
      const report = await resultResponse.json();
      assert.equal(report.calculation_version,'0.6.0');
      assert.ok(report.event_count>0);
      assert.ok(report.events.every(e => e.next_day_analysis));
      await page.getByRole('heading',{name:'V1 次日偏离摘要',exact:true}).waitFor();
      const prefix = viewport.width===1440 ? 'desktop' : 'mobile';
      await page.screenshot({path:path.join(out,`${prefix}-summary.png`)});
      const candidate = report.events.find(e => e.next_day_analysis?.outcome?.assessment === 'below_first' && report.events.filter(x => x.code === e.code).length === 1);
      assert.ok(candidate,'Need a real completed next-day decline for release acceptance');
      await page.getByLabel('搜索复盘股票').fill(candidate.code);
      const expand = page.getByRole('button',{name:/查看 \d{6} 复盘证据/}).first();
      await expand.click();
      assert.equal(await expand.getAttribute('aria-expanded'),'true');
      const analysis = page.getByRole('region',{name:'V1 次日偏离分析',exact:true});
      await analysis.waitFor();
      await analysis.scrollIntoViewIfNeeded();
      assert.ok((await analysis.innerText()).includes('当时为什么触发'));
      assert.ok((await analysis.innerText()).includes('后来实际发生什么'));
      assert.ok((await analysis.innerText()).includes('为什么偏离：待核查，尚非结论'));
      await page.screenshot({path:path.join(out,`${prefix}-analysis.png`)});
      const bounds = await analysis.boundingBox();
      const pageWidth = await page.evaluate(() => ({width:innerWidth,scroll:document.documentElement.scrollWidth}));
      assert.ok(pageWidth.scroll<=pageWidth.width+2,JSON.stringify(pageWidth));
      assert.ok(bounds.width<=viewport.width+2,JSON.stringify(bounds));
      assert.equal(await page.locator('vite-error-overlay').count(),0);
      await page.getByRole('button',{name:'报告归档',exact:true}).click();
      await page.getByRole('heading',{name:'自动报告运行',exact:true}).waitFor();
      await page.getByRole('button',{name:'刷新运行记录',exact:true}).click();
      await page.getByRole('button',{name:'查看报告',exact:true}).first().waitFor({timeout:45000});
      await page.getByRole('button',{name:'查看报告',exact:true}).first().click();
      await page.getByRole('heading',{name:'归档报告 · 原始修订快照',exact:true}).waitFor();
      await page.screenshot({path:path.join(out,`${prefix}-archive.png`)});
      evidence.runs.push({viewport,url:page.url(),title:await page.title(),version:report.calculation_version,events:report.event_count,nextDay:report.next_day_metrics,errors,layout:pageWidth});
      assert.deepEqual(errors,[]);
      await context.close();
    }
    console.log(JSON.stringify(evidence,null,2));
    await fs.writeFile(path.join(out,'online-qa.json'),JSON.stringify(evidence,null,2));
  } finally {await browser.close();}
})().catch(e => {console.error(e);process.exit(1);});
